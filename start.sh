#!/bin/bash
python tgbot.py
# Выход при ошибке
set -e

# Выводим информацию о запуске
echo "==================================="
echo "ЗАПУСК TELEGRAM БОТА С ПОГОДОЙ"
echo "==================================="
echo "Время запуска: $(date)"
echo "Текущая директория: $(pwd)"
echo ""

# Проверяем наличие файла .env
if [ -f .env ]; then
    echo "✅ Файл .env найден, загружаем переменные окружения"
    export $(grep -v '^#' .env | xargs)
else
    echo "⚠️ Файл .env не найден, используем переменные окружения системы"
fi

# Проверяем наличие токенов
if [ -z "$TELEGRAM_TOKEN" ]; then
    echo "❌ ОШИБКА: Не задан TELEGRAM_TOKEN"
    echo "Пожалуйста, установите токен в переменных окружения или в файле .env"
    exit 1
fi

if [ -z "$GISMETEO_TOKEN" ]; then
    echo "⚠️ ВНИМАНИЕ: Не задан GISMETEO_TOKEN"
    echo "Бот будет работать с ограниченной функциональностью"
fi

# Проверяем наличие основного файла бота
if [ ! -f "weather_bot.py" ]; then
    echo "❌ ОШИБКА: Файл weather_bot.py не найден!"
    exit 1
fi

echo ""
echo="✅ Все проверки пройдены успешно"
echo="🚀 Запускаем бота..."
echo "==================================="
echo ""

# Запускаем бота
python weather_bot.py
